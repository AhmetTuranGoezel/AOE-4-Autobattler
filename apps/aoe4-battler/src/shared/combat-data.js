function buildingEnhancement(id, overrides = {}) {
  const base = BUILDING_ENHANCEMENT_DEFS[id];
  return {
    ...cloneValue(base),
    ...cloneValue(overrides),
  };
}

function makeBuilding(base, enhancements = [], overrides = {}) {
  return {
    meleeArmor: 0,
    baseAttackType: "ranged",
    garrisonAttackType: "ranged",
    baseArrowBonus: { Ship: 10 },
    garrisonArrowBonus: { Ship: 10 },
    emplacements: [],
    lockedEmplacements: [],
    emplacementMode: "toggle",
    civs: [],
    enhancements: enhancements.map((entry) =>
      typeof entry === "string" ? buildingEnhancement(entry) : cloneValue(entry)
    ),
    ...cloneValue(base),
    ...cloneValue(overrides),
  };
}

