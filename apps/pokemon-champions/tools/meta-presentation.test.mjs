import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { selectMetaDataset, teamsForPokemon, mapTournamentTeam } from "../src/meta-model.js";
import { presentBuilds, presentImportNotes, renderMetaUsage, renderPublishedTeam } from "../src/meta-view.js";
import { sourcePortrait } from "../src/source-portraits.js";
const read = file => JSON.parse(readFileSync(new URL(file, import.meta.url)));
const data = read("../champions-data.json");
data.tournamentMeta = read("../champions-meta.json");
data.tournamentTeams = read("../champions-teams.json");
selectMetaDataset(data, "M-C");
const hydreigon = data.pokemon.find(m => m.slug === "hydreigon");
const florges = data.pokemon.find(m => m.slug === "florges");
const before = JSON.stringify(data);
const build = presentBuilds(hydreigon.metaUsage)[0];
assert.equal(build.percent, 75);
assert.equal(build.evidence.count, 3);
assert.equal(build.evidence.sampleSize, 4);
assert.deepEqual(build.evidence.natures, [{ id: "modest", count: 3, percent: 100 }]);
const hydroHtml = renderMetaUsage(hydreigon, data);
assert.match(hydroHtml, /data-meta-browse-teams/);
assert.match(hydroHtml, /meta-dashboard-lower/);
assert.equal((hydroHtml.match(/data-meta-category=/g) || []).length, 4);
assert.ok(hydroHtml.indexOf('data-meta-category="natures"') < hydroHtml.indexOf('data-build-card'), "Usage dashboard precedes builds");
assert.ok(hydroHtml.indexOf('meta-dashboard-lower') < hydroHtml.indexOf('data-build-card'));
assert.doesNotMatch(hydroHtml, /data-detail-tab="builds"|All builds & Stat Lab/, "Dashboard has no obsolete Builds navigation");
assert.match(hydroHtml, /75%/);
assert.match(hydroHtml, /3\/3/);
assert.match(hydroHtml, /aggregate usage/);
assert.match(hydroHtml, /separate from aggregate sample/);
assert.match(hydroHtml, /75.3%/, "Overall Nature remains a distinct distribution");
assert.equal((hydroHtml.match(/data-build-card/g) || []).length, 2);
assert.match(hydroHtml, /alt="Sneasler"/);
assert.match(hydroHtml, /35.5%/);
const flowerHtml = renderMetaUsage(florges, data, {}, { view: "builds" });
const flowerDashboard = renderMetaUsage(florges, data);
assert.equal((flowerDashboard.match(/data-build-card/g) || []).length, 2);
assert.match(flowerDashboard, /data-meta-more="spreads" data-meta-next="6"/);
const flowerExpanded = renderMetaUsage(florges, data, { spreads: 6 });
assert.equal((flowerExpanded.match(/data-build-card/g) || []).length, 3, "Show more exposes remaining exact builds in the dashboard");
assert.match(flowerExpanded, /data-meta-browse-teams/);
assert.equal((flowerExpanded.match(/Nature: unavailable from captured sets/g) || []).length, 3);
assert.equal(presentBuilds(florges.metaUsage).length, 3);
assert.ok(presentBuilds(florges.metaUsage).every(b => b.evidence === null));
assert.equal((flowerHtml.match(/Nature: unavailable from captured sets/g) || []).length, 3);
assert.doesNotMatch(flowerHtml, /data-meta-joint/);
assert.equal((flowerHtml.match(/data-meta-spread/g) || []).length, 3);
// Aggregate and overall Nature changes may NEVER produce captured evidence.
const aggregateOnly = structuredClone(florges.metaUsage);
aggregateOnly.natures = [{ id: "modest", percent: 100 }];
assert.ok(presentBuilds(aggregateOnly).every(b => b.evidence === null));
const mismatch = structuredClone(hydreigon.metaUsage);
mismatch.observedSpreads[0].stats = { hp: 32, atk: 0, def: 0, spa: 32, spd: 2, spe: 0 };
assert.equal(presentBuilds(mismatch)[0].evidence, null);
assert.equal(presentBuilds(mismatch).at(-1).percent, null, "Captured-only build must not claim aggregate usage");
const multiNature = structuredClone(hydreigon);
multiNature.metaUsage.observedSpreads[0].natures = [{ id: "modest", count: 2, percent: 66.7 }, { id: "timid", count: 1, percent: 33.3 }];
const multiHtml = renderMetaUsage(multiNature, data);
assert.match(multiHtml, /2\/3/);
assert.match(multiHtml, /1\/3/);
assert.match(multiHtml, /data-meta-joint="0" data-meta-nature="modest"/);
assert.match(multiHtml, /data-meta-joint="0" data-meta-nature="timid"/);
const browser = renderMetaUsage(hydreigon, data, {}, { view: "teams", teamKind: "tournament" });
assert.match(browser, /data-meta-open-team/);
assert.match(browser, /data-meta-dashboard/);
assert.doesNotMatch(browser, /meta-set-card|data-meta-import=|<details/, "Collapsed browser renders no six-set payloads or duplicate import controls");
assert.equal((browser.match(/data-team-card=/g) || []).length, 6);
assert.equal((browser.match(/class="meta-avatar/g) || []).length, 36);
assert.equal((browser.match(/<img /g) || []).length, 36, "Every collapsed card shows six sprites, including source-only identities");
assert.match(browser, /Floette \(source portrait only\)/);
assert.match(browser, /import mapping remains unresolved/);
assert.match(browser, /sprites\/pokemon\/670\.png/);
assert.doesNotMatch(browser, /sprites\/pokemon\/10061\.png/, "Generic source Floette is not substituted with the eligible Eternal form");
const sourceTeam = teamsForPokemon(data, hydreigon).find(t => t.members.some(set => set.form === "floette"));
const sourceMapping = mapTournamentTeam(sourceTeam, data);
const sourceDetail = renderPublishedTeam(sourceTeam, data);
assert.match(sourceDetail, /sprites\/pokemon\/670\.png/);
assert.match(sourceDetail, /Unknown Pokémon\/form slug: floette/);
assert.match(sourceDetail, /data-meta-import="[^"]+" disabled/);
assert.deepEqual(mapTournamentTeam(sourceTeam, data), sourceMapping, "Source portraits never repair or mutate mechanical mapping");
for (const [identity, dex] of [["floette", 670], ["gothitelle", 576], ["kingdra", 230], ["octillery", 224]]) {
  assert.equal(sourcePortrait(identity).sourceOnly, true);
  assert.ok(sourcePortrait(identity).sprite.endsWith(`/${dex}.png`));
}
for (const identity of ["tauros-paldea", "floette-mega", "unmapped-test-form", "toString", "__proto__"]) {
  assert.equal(sourcePortrait(identity), null, "Ambiguous or unrecognized identities are not guessed");
}
const team = teamsForPokemon(data, hydreigon).find(t => !mapTournamentTeam(t, data).errors.length);
const detail = renderPublishedTeam(team, data);
assert.equal((detail.match(/class="meta-set-card"/g) || []).length, 6);
assert.equal((detail.match(/data-meta-import=/g) || []).length, 1);
assert.equal((detail.match(/data-meta-opponent=/g) || []).length, 1);
assert.doesNotMatch(detail, /Stat Points undisclosed|Import notes \(6\)|<details/);
const unknown = structuredClone(team); unknown.members[0].form = "unmapped-test-form";
assert.match(renderPublishedTeam(unknown, data), /Resolve before importing/);
assert.match(renderPublishedTeam(unknown, data), /unmapped-test-form/);
assert.match(renderPublishedTeam(unknown, data), /data-meta-import="[^"]+" disabled/);
assert.match(renderPublishedTeam(unknown, data), /image unavailable/, "Unrecognized source forms retain a labelled image fallback");
const undisclosedTeam = structuredClone(team);
undisclosedTeam.members.forEach(set => { set.statsKnown = false; });
const undisclosedHtml = renderPublishedTeam(undisclosedTeam, data);
assert.match(undisclosedHtml, /6\/6 spreads unavailable/);
assert.equal((undisclosedHtml.match(/class="meta-spread-missing"/g) || []).length, 6);
assert.doesNotMatch(undisclosedHtml, /Stat Points undisclosed|Resolve before importing/);
const unconfirmed = structuredClone(team);
const firstMon = data.pokemon.find(mon => mon.slug === unconfirmed.members[0].form);
const [unconfirmedId, unconfirmedMove] = Object.entries(data.moves).find(([id]) => !firstMon.moves.includes(Number(id)));
unconfirmed.members[0].moves = [unconfirmedMove.slug || unconfirmedMove.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")];
assert.ok(!firstMon.moves.includes(Number(unconfirmedId)));
const warningMapping = mapTournamentTeam(unconfirmed, data);
assert.ok(warningMapping.warnings.some(note => note.includes("not confirmed in the current learnset")));
assert.match(renderPublishedTeam(unconfirmed, data), /meta-import-warnings/);
assert.match(renderPublishedTeam(unconfirmed, data), /Source set warnings/);
assert.match(renderPublishedTeam(unconfirmed, data), /not confirmed in the current learnset/);
const missingMetadata = { ...structuredClone(team), id: "test-missing-meta", kind: "tournament", placement: null, player: null, event: null, date: null, record: { wins: 0, losses: null } };
const missingBrowser = renderMetaUsage({ ...hydreigon, metaUsage: { ...hydreigon.metaUsage, teamIds: [missingMetadata.id] } }, { ...data, tournamentTeams: { teams: [missingMetadata] } }, {}, { view: "teams" });
assert.match(missingBrowser, /Placement not supplied/);
assert.match(missingBrowser, /Player not supplied/);
assert.match(missingBrowser, /Date unavailable/);
assert.match(missingBrowser, /Record not supplied/);
assert.doesNotMatch(missingBrowser, /0–null|0–undefined/);
const loadingBrowser = renderMetaUsage(hydreigon, { ...data, tournamentTeams: null, tournamentTeamsError: "Temporary failure" }, {}, { view: "teams" });
assert.match(loadingBrowser, /data-meta-dashboard/);
assert.match(loadingBrowser, /Temporary failure/);
assert.match(loadingBrowser, /data-meta-retry/);
const mapping = mapTournamentTeam(team, data), oldWarnings = [...mapping.warnings];
assert.ok(presentImportNotes(mapping).notes.every(note => !note.includes("Stat Points undisclosed")));
assert.ok(presentImportNotes(mapping).issues.every(note => !note.includes("Stat Points undisclosed") && !note.includes("retained pre-Mega")));
assert.deepEqual(mapping.warnings, oldWarnings);
assert.equal(JSON.stringify(data), before, "Rendering must not change raw evidence, mapping, snapshots or mechanics");
console.log("Meta presentation passed: compact dashboard order/pagination, exact Nature evidence, six source sprites, focused teams, quiet disclosure, visible errors/warnings, missing metadata and data immutability");
